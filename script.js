let currentLanguage = 'en';
let scriptsData = [];
let selectedNames = [];
let currentName = null;
let searchTerm = '';
let pendingAction = null;

function t(key) {
    return (translations[currentLanguage] && translations[currentLanguage][key]) || key;
}

function bridge(event, payload) {
    if (typeof mta !== 'undefined' && mta.triggerEvent) {
        if (payload === undefined) {
            mta.triggerEvent(event);
        } else {
            mta.triggerEvent(event, payload);
        }
    }
}

/* ---------- Language ---------- */
let suppressLangNotify = false;

function loadLanguage(lang) {
    if (!translations[lang]) {
        return;
    }
    suppressLangNotify = true;
    setLanguage(lang);
    suppressLangNotify = false;
}

function setLanguage(lang) {
    currentLanguage = lang;

    if (!suppressLangNotify && typeof mta !== 'undefined' && mta.triggerEvent) {
        mta.triggerEvent("TScompiler.setLanguage", lang);
    }

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.textContent === lang.toUpperCase());
    });

    document.querySelectorAll('[data-lang]').forEach(el => {
        const key = el.getAttribute('data-lang');
        if (!translations[lang] || !translations[lang][key]) {
            return;
        }
        if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = translations[lang][key];
        } else if (el.hasAttribute('title')) {
            el.title = translations[lang][key];
        } else {
            el.textContent = translations[lang][key];
        }
    });

    renderScripts();
    if (currentName !== null) {
        const script = scriptsData.find(s => s.name === currentName);
        if (script) {
            updateFilesList(script);
        }
    }
}

/* ---------- Data load (preserves selection) ---------- */
function loadScriptsData(scripts) {
    if (!scripts) {
        scripts = [];
    }
    if (typeof scripts === 'string') {
        try {
            scripts = JSON.parse(scripts);
        } catch (e) {
            scripts = [];
        }
    }
    if (!Array.isArray(scripts)) {
        scripts = [scripts];
    }

    scriptsData = scripts;

    const validNames = scriptsData.map(s => s && s.name).filter(Boolean);
    selectedNames = selectedNames.filter(name => validNames.indexOf(name) !== -1);
    if (currentName !== null && validNames.indexOf(currentName) === -1) {
        currentName = null;
    }

    renderScripts();

    if (currentName !== null) {
        const script = scriptsData.find(s => s.name === currentName);
        if (script) {
            updateFilesList(script);
        }
    } else {
        clearFilesList();
    }
}

/* ---------- Render list ---------- */
function renderScripts() {
    const list = document.getElementById('scriptsList');
    const prevScroll = list.scrollTop;
    list.innerHTML = '';

    if (!scriptsData || scriptsData.length === 0) {
        const empty = document.createElement('div');
        empty.className = 'empty';
        empty.textContent = t('no-scripts');
        list.appendChild(empty);
        updateSelectionCounter();
        return;
    }

    scriptsData.forEach(script => {
        if (!script || !script.name) {
            return;
        }
        list.appendChild(createScriptRow(script));
    });

    applySearchFilter();
    list.scrollTop = prevScroll;
    updateSelectionCounter();
    updateSelectAllState();
}

function createScriptRow(script) {
    const name = script.name;
    const row = document.createElement('div');
    row.className = 'row';
    row.setAttribute('data-name', name);

    if (currentName === name) {
        row.classList.add('selected');
    }

    const isChecked = selectedNames.indexOf(name) !== -1;

    const protectOn = !!script.hasProtection;
    const protectBadge = protectOn ? 'protect-on' : 'protect-off';
    const protectLabel = protectOn ? t('protect-on') : t('protect-off');

    const hasClient = script.clientFiles && script.clientFiles.length > 0;
    let clientState = 'none';
    if (hasClient) {
        clientState = script.clientCompiled ? 'compiled' : 'uncompiled';
    }

    row.setAttribute('data-clientstate', clientState);
    row.setAttribute('data-protected', protectOn ? 'true' : 'false');

    const check = document.createElement('input');
    check.type = 'checkbox';
    check.className = 'row-check';
    check.checked = isChecked;
    check.addEventListener('change', function (e) {
        e.stopPropagation();
        toggleScriptSelection(name, check.checked);
    });
    check.addEventListener('click', function (e) {
        e.stopPropagation();
    });

    const nameEl = document.createElement('div');
    nameEl.className = 'row-name';
    nameEl.textContent = name;

    const pBadge = document.createElement('span');
    pBadge.className = 'badge ' + protectBadge;
    pBadge.textContent = protectLabel;

    row.appendChild(check);
    row.appendChild(nameEl);
    row.appendChild(pBadge);

    if (clientState !== 'none') {
        const sBadge = document.createElement('span');
        sBadge.className = 'badge ' + clientState;
        sBadge.textContent = clientState === 'compiled' ? t('status-compiled') : t('status-uncompiled');
        row.appendChild(sBadge);
    }

    row.addEventListener('click', function () {
        selectScript(name);
    });

    return row;
}

/* ---------- Filtering (visibility toggle, no rebuild) ---------- */
let statusFilter = 'all';

function setStatusFilter(filter, btn) {
    statusFilter = filter;
    document.querySelectorAll('.filter-chip').forEach(chip => chip.classList.remove('active'));
    if (btn) {
        btn.classList.add('active');
    }
    applySearchFilter();
    updateSelectAllState();
}

function filterScripts() {
    searchTerm = document.getElementById('searchInput').value.toLowerCase();
    applySearchFilter();
}

function applySearchFilter() {
    const rows = document.querySelectorAll('#scriptsList .row');
    rows.forEach(row => {
        const name = (row.getAttribute('data-name') || '').toLowerCase();
        const matchesSearch = name.indexOf(searchTerm) !== -1;

        let matchesStatus = true;
        if (statusFilter === 'compiled') {
            matchesStatus = row.getAttribute('data-clientstate') === 'compiled';
        } else if (statusFilter === 'uncompiled') {
            matchesStatus = row.getAttribute('data-clientstate') === 'uncompiled';
        } else if (statusFilter === 'protected') {
            matchesStatus = row.getAttribute('data-protected') === 'true';
        }

        row.style.display = (matchesSearch && matchesStatus) ? '' : 'none';
    });
}

function visibleRows() {
    return Array.prototype.filter.call(
        document.querySelectorAll('#scriptsList .row'),
        row => row.style.display !== 'none'
    );
}

/* ---------- Selection ---------- */
function toggleSelectAll() {
    const selectAll = document.getElementById('selectAll');
    const rows = visibleRows();

    rows.forEach(row => {
        const name = row.getAttribute('data-name');
        const check = row.querySelector('.row-check');
        if (selectAll.checked) {
            if (selectedNames.indexOf(name) === -1) {
                selectedNames.push(name);
            }
            check.checked = true;
        } else {
            selectedNames = selectedNames.filter(n => n !== name);
            check.checked = false;
        }
    });

    updateSelectionCounter();
}

function toggleScriptSelection(name, checked) {
    if (checked) {
        if (selectedNames.indexOf(name) === -1) {
            selectedNames.push(name);
        }
    } else {
        selectedNames = selectedNames.filter(n => n !== name);
    }
    updateSelectionCounter();
    updateSelectAllState();
}

function updateSelectAllState() {
    const selectAll = document.getElementById('selectAll');
    if (!selectAll) {
        return;
    }
    const rows = visibleRows();
    if (rows.length === 0) {
        selectAll.checked = false;
        return;
    }
    selectAll.checked = rows.every(row => selectedNames.indexOf(row.getAttribute('data-name')) !== -1);
}

function updateSelectionCounter() {
    const counter = document.getElementById('selectionCounter');
    if (counter) {
        counter.textContent = selectedNames.length;
    }
}

function selectScript(name) {
    currentName = name;
    document.querySelectorAll('#scriptsList .row').forEach(row => {
        row.classList.toggle('selected', row.getAttribute('data-name') === name);
    });
    const script = scriptsData.find(s => s.name === name);
    if (script) {
        updateFilesList(script);
    }
}

/* ---------- Files preview ---------- */
function clearFilesList() {
    document.getElementById('currentResName').innerHTML = '&mdash;';
    const filesEl = document.getElementById('filesList');
    filesEl.innerHTML = '';
    const empty = document.createElement('div');
    empty.className = 'empty small';
    empty.textContent = t('no-selection');
    filesEl.appendChild(empty);
}

function updateFilesList(script) {
    document.getElementById('currentResName').textContent = script.name;
    const filesEl = document.getElementById('filesList');
    filesEl.innerHTML = '';

    const files = [
        ...(script.clientFiles || []).map(f => ({ name: f, type: 'client' })),
        ...(script.serverFiles || []).map(f => ({ name: f, type: 'server' }))
    ];

    if (files.length === 0) {
        const empty = document.createElement('div');
        empty.className = 'empty small';
        empty.textContent = t('no-files');
        filesEl.appendChild(empty);
        return;
    }

    const companions = script.companions || {};

    files.forEach(file => {
        const row = document.createElement('div');
        row.className = 'file-row';

        const nameEl = document.createElement('span');
        nameEl.className = 'file-name';
        nameEl.textContent = file.name;

        const typeEl = document.createElement('span');
        typeEl.className = 'file-type ' + file.type;
        typeEl.textContent = file.type === 'client' ? t('type-client') : t('type-server');

        row.appendChild(nameEl);
        row.appendChild(typeEl);
        filesEl.appendChild(row);

        if (companions[file.name]) {
            const compRow = document.createElement('div');
            compRow.className = 'file-row companion';

            const compName = document.createElement('span');
            compName.className = 'file-name';
            compName.textContent = '↳ ' + companions[file.name];

            const compType = document.createElement('span');
            compType.className = 'file-type ' + file.type;
            compType.textContent = file.type === 'client' ? t('type-client') : t('type-server');

            compRow.appendChild(compName);
            compRow.appendChild(compType);
            filesEl.appendChild(compRow);
        }
    });
}

/* ---------- Confirmation modal ---------- */
function showConfirmation(action) {
    const compileClient = document.getElementById('compileClient').checked;
    const compileServer = document.getElementById('compileServer').checked;
    const enableProtection = document.getElementById('enableProtection').checked;
    const restartAfterCompile = document.getElementById('restartAfterCompile').checked;

    if (action === 'compileSelected' && selectedNames.length === 0) {
        flashStatus(t('alert-no-scripts'));
        return;
    }
    if (!compileClient && !compileServer) {
        flashStatus(t('alert-no-options'));
        return;
    }

    const yes = t('yes');
    const no = t('no');
    let message;

    if (action === 'compileSelected') {
        message = t('compile-selected-confirm')
            .replace('{scripts}', selectedNames.join(', '))
            .replace('{client}', compileClient ? yes : no)
            .replace('{server}', compileServer ? yes : no)
            .replace('{protection}', enableProtection ? yes : no)
            .replace('{restart}', restartAfterCompile ? yes : no);
    } else {
        message = t('compile-all-confirm')
            .replace('{client}', compileClient ? yes : no)
            .replace('{server}', compileServer ? yes : no)
            .replace('{protection}', enableProtection ? yes : no)
            .replace('{restart}', restartAfterCompile ? yes : no);
    }

    document.getElementById('modalTitle').textContent = t('confirmation-title');
    document.getElementById('modalMessage').textContent = message;
    document.getElementById('modalConfirm').textContent = t('btn-accept');
    document.getElementById('modalCancel').textContent = t('btn-cancel');

    pendingAction = action;
    document.getElementById('confirmationModal').classList.add('show');
}

function confirmAction() {
    if (pendingAction === 'compileSelected') {
        compileSelected();
    } else if (pendingAction === 'compileAll') {
        compileAllServer();
    }
    closeModal();
}

function closeModal() {
    document.getElementById('confirmationModal').classList.remove('show');
    pendingAction = null;
}

/* ---------- Build & send task payload ---------- */
function buildOptions() {
    return {
        compileClient: document.getElementById('compileClient').checked,
        compileServer: document.getElementById('compileServer').checked,
        enableProtection: document.getElementById('enableProtection').checked,
        restartAfterCompile: document.getElementById('restartAfterCompile').checked
    };
}

function compileSelected() {
    const opt = buildOptions();
    const tasks = selectedNames.map(name => ({
        resourceName: name,
        compileClient: opt.compileClient,
        compileServer: opt.compileServer,
        enableProtection: opt.enableProtection,
        restartAfterCompile: opt.restartAfterCompile
    }));
    sendCompilation(tasks);
}

function compileAllServer() {
    const opt = buildOptions();
    const tasks = [{
        resourceName: 'ALL_SERVER_SCRIPTS',
        compileClient: opt.compileClient,
        compileServer: opt.compileServer,
        enableProtection: opt.enableProtection,
        restartAfterCompile: opt.restartAfterCompile
    }];
    sendCompilation(tasks);
}

function sendCompilation(tasks) {
    setBusyStatus(t('starting'));
    bridge('TScompiler.startCompilation', JSON.stringify(tasks));
}

/* ---------- Status / progress ---------- */
function flashStatus(text) {
    const dot = document.getElementById('statusDot');
    const txt = document.getElementById('statusText');
    dot.className = 'status-dot busy';
    txt.textContent = text;
    document.getElementById('progressTrack').classList.remove('show');
    setTimeout(resetStatus, 2600);
}

function setBusyStatus(text) {
    document.getElementById('statusDot').className = 'status-dot busy';
    document.getElementById('statusText').textContent = text;
    document.getElementById('progressTrack').classList.add('show');
    document.getElementById('progressFill').style.width = '5%';
}

function resetStatus() {
    document.getElementById('statusDot').className = 'status-dot';
    document.getElementById('statusText').textContent = t('status-idle');
    document.getElementById('progressTrack').classList.remove('show');
    document.getElementById('progressFill').style.width = '0%';
}

let compileTotalFiles = 0;

function updateCompilationProgress(data) {
    if (!data) {
        return;
    }

    if (data.type === 'progress') {
        const total = Number(data.total) || 0;
        if (total > compileTotalFiles) {
            compileTotalFiles = total;
        }
        let pct = 5;
        if (compileTotalFiles > 0) {
            const remaining = total;
            const done = compileTotalFiles - remaining;
            pct = Math.max(5, Math.min(95, Math.round((done / compileTotalFiles) * 100)));
        }
        document.getElementById('statusDot').className = 'status-dot busy';
        document.getElementById('statusText').textContent = data.message || '';
        const track = document.getElementById('progressTrack');
        track.classList.add('show');
        document.getElementById('progressFill').style.width = pct + '%';
    } else if (data.type === 'status') {
        compileTotalFiles = 0;
        setBusyStatus(data.message || t('starting'));
    } else if (data.type === 'complete') {
        document.getElementById('statusDot').className = 'status-dot done';
        document.getElementById('statusText').textContent = data.message || t('completed');
        document.getElementById('progressFill').style.width = '100%';
        compileTotalFiles = 0;
        bridge('TScompiler.refreshScriptsList');
        setTimeout(resetStatus, 3000);
    }
}

