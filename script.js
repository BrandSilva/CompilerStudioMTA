/* ---------- Dragging + centering ---------- */
function initWindow() {
    const win = document.getElementById('window');
    const bar = document.getElementById('titlebar');

    const left = Math.max(0, Math.round((window.innerWidth - win.offsetWidth) / 2));
    const top = Math.max(0, Math.round((window.innerHeight - win.offsetHeight) / 2));
    win.style.left = left + 'px';
    win.style.top = top + 'px';

    let dragging = false;
    let offsetX = 0;
    let offsetY = 0;

    bar.addEventListener('mousedown', function (e) {
        if (e.target.closest('.win-btn') || e.target.closest('.lang-btn')) {
            return;
        }
        dragging = true;
        offsetX = e.clientX - win.offsetLeft;
        offsetY = e.clientY - win.offsetTop;
        e.preventDefault();
    });

    document.addEventListener('mousemove', function (e) {
        if (!dragging) {
            return;
        }
        let nl = e.clientX - offsetX;
        let nt = e.clientY - offsetY;
        nl = Math.max(0, Math.min(nl, window.innerWidth - win.offsetWidth));
        nt = Math.max(0, Math.min(nt, window.innerHeight - win.offsetHeight));
        win.style.left = nl + 'px';
        win.style.top = nt + 'px';
    });

    document.addEventListener('mouseup', function () {
        dragging = false;
    });
}

window.onload = function () {
    initWindow();
    resetStatus();
    bridge('TScompiler.requestScriptsList');
};
